#!/usr/bin/env python3
"""Generates two display assets. Run from the project root: python3 assets/tools/make_gauge_assets.py

needle_tip.c     The outer part of needle.c only. The inner part of the needle is always
                 hidden under the centre circle, and LVGL has to redraw the whole bounding
                 box of a rotated image, so the full-length needle made every frame redraw
                 about five times more screen than the part you can see.
circle_shadow.c  A soft ring of shadow around the centre circle, as an alpha-only image.
                 LVGL's own shadow style rebuilds a 45 KB blur every time it is drawn
                 (about 40 ms a frame here). A fixed image costs almost nothing.
"""
import math, os, re

HERE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

# ---- needle_tip: crop needle.c ----
NEEDLE_W, NEEDLE_H = 241, 21
PIVOT_COL = 3            # column of needle.c that sits on the gauge centre
CIRCLE_RADIUS = 140      # centre circle (280 px across)
KEEP_UNDER_CIRCLE = 12   # px of needle kept under the circle edge, so no gap can show
CROP_COL = PIVOT_COL + CIRCLE_RADIUS - KEEP_UNDER_CIRCLE   # first column kept

# ---- circle_shadow ----
SHADOW_REACH = 10        # px the shadow extends beyond the circle
SHADOW_PEAK = 150        # alpha (0-255) right at the circle's edge


def emit(name, cf, w, h, data, comment):
    lines = ["// Generated by assets/tools/make_gauge_assets.py. Do not edit by hand.",
             "// " + comment, '#include "lvgl.h"', "",
             "static const uint8_t %s_map[] = {" % name]
    for i in range(0, len(data), 24):
        lines.append("  " + ", ".join("0x%02x" % b for b in data[i:i + 24]) + ",")
    lines += ["};", "", "const lv_image_dsc_t %s = {" % name,
              "  .header.cf = %s," % cf, "  .header.magic = LV_IMAGE_HEADER_MAGIC,",
              "  .header.w = %d," % w, "  .header.h = %d," % h,
              "  .data_size = %d," % len(data), "  .data = %s_map," % name, "};", ""]
    with open(os.path.join(HERE, name + ".c"), "w") as f:
        f.write("\n".join(lines))
    print("%s.c: %d x %d, %d bytes" % (name, w, h, len(data)))


src = open(os.path.join(HERE, "needle.c")).read()
body = src[src.index("needle_map[]"):src.index("const lv_image_dsc_t needle")]
px = [int(t, 16) for t in re.findall(r"0x([0-9a-fA-F]{2})", body)]
assert len(px) == NEEDLE_W * NEEDLE_H * 3, len(px)
colour, alpha = px[:NEEDLE_W * NEEDLE_H * 2], px[NEEDLE_W * NEEDLE_H * 2:]
new_w = NEEDLE_W - CROP_COL
out = []
for y in range(NEEDLE_H):                       # RGB565 plane, 2 bytes a pixel
    out += colour[(y * NEEDLE_W + CROP_COL) * 2:(y + 1) * NEEDLE_W * 2]
for y in range(NEEDLE_H):                       # alpha plane
    out += alpha[y * NEEDLE_W + CROP_COL:(y + 1) * NEEDLE_W]
emit("needle_tip", "LV_COLOR_FORMAT_RGB565A8", new_w, NEEDLE_H, out,
     "needle.c from column %d. Pivot x = %d, so the gauge centre is %d px left of this image."
     % (CROP_COL, PIVOT_COL - CROP_COL, CROP_COL - PIVOT_COL))

size = 2 * (CIRCLE_RADIUS + SHADOW_REACH)
c = (size - 1) / 2.0
shadow = []
for y in range(size):
    for x in range(size):
        r = math.hypot(x - c, y - c)
        if r <= CIRCLE_RADIUS - 3:
            a = 0                                # hidden under the circle anyway
        elif r <= CIRCLE_RADIUS:
            a = SHADOW_PEAK
        elif r < CIRCLE_RADIUS + SHADOW_REACH:
            t = 1.0 - (r - CIRCLE_RADIUS) / SHADOW_REACH
            a = int(SHADOW_PEAK * t * t + 0.5)   # fades out smoothly
        else:
            a = 0
        shadow.append(a)
emit("circle_shadow", "LV_COLOR_FORMAT_A8", size, size, shadow,
     "Shadow ring for the %d px circle: %d px reach, peak alpha %d." % (2 * CIRCLE_RADIUS, SHADOW_REACH, SHADOW_PEAK))
# needle.c sat at x offset 116 from centre. Keep the same pixels in the same place.
print("ui.cpp constants: needle x offset %d, pivot x %d" % (116 - NEEDLE_W // 2 + CROP_COL + new_w // 2, PIVOT_COL - CROP_COL))
